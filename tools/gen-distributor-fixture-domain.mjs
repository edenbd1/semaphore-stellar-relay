// Domain-separated fixture for the ConfidentialDistributor: a 3-member group, each member's
// proof bound to a DISTINCT recipient (message = reduce8(keccak(recipient_xdr))) and all to one
// campaign scope that is DOMAIN-BOUND to the distributor's own address:
//   scope = keccak256( ascii(CONTRACT strkey) || SCOPE_SEED ) >> 8
// On-chain claim() recomputes this via domain_scope_hash(current_contract_address, scope_seed).
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof, verifyProof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex, concat, toUtf8Bytes, getBytes } from "ethers"
import { StrKey, nativeToScVal, Address } from "@stellar/stellar-sdk"
import { readFileSync, writeFileSync } from "fs"
import { tmpdir } from "os"
import { join } from "path"

const VKEY_PATH = "/Users/eden/data/semaphore-stellar-relay/fixtures/vkey-depth2.json"
const OUT = "/Users/eden/data/semaphore-stellar-relay/contracts/distributor/src/fixture.rs"
const ART = join(tmpdir(), "snark-artifacts", "semaphore", "4.13.0")
const SNARK = { wasm: join(ART, "semaphore-2.wasm"), zkey: join(ART, "semaphore-2.zkey") }

const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()
const signalFor = (g) => BigInt(keccak256("0x" + nativeToScVal(new Address(g), { type: "address" }).toXDR("hex")))

// Fixed distributor contract address the campaign scope is bound to.
const CONTRACT_ID = getBytes(keccak256(toUtf8Bytes("semaphore-stellar/distributor/domain-v1")))
const CONTRACT = StrKey.encodeContract(Buffer.from(CONTRACT_ID))

const SCOPE_SEED_HEX = "5c".repeat(32)
const rawscopeHex = keccak256(concat([toUtf8Bytes(CONTRACT), getBytes("0x" + SCOPE_SEED_HEX)]))
const scopeBig = BigInt(rawscopeHex)
if (toBeHex(scopeBig, 32) !== rawscopeHex) throw new Error("scope encoding mismatch")

const contractAddr = (n) => StrKey.encodeContract(Buffer.alloc(32, n))
const RECIP_A = contractAddr(11)
const RECIP_B = contractAddr(22)

const A = new Identity(), B = new Identity(), C = new Identity()
const group = new Group([A.commitment, B.commitment, C.commitment])
const vkey = JSON.parse(readFileSync(VKEY_PATH, "utf8"))

async function mk(id, recipient) {
    const signal = signalFor(recipient)
    const p = await generateProof(id, group, signal, scopeBig, 2, SNARK)
    if (!(await verifyProof(p))) throw new Error("lib verifyProof failed")
    const u = unpackGroth16Proof(p.points)
    const pub = [p.merkleTreeRoot.toString(), p.nullifier.toString(), hash(signal), hash(scopeBig)]
    if (!(await snarkjs.groth16.verify(vkey, pub, u))) throw new Error("ground-truth verify failed")
    return { root: p.merkleTreeRoot.toString(), nullifier: p.nullifier.toString(), u }
}
const pa = await mk(A, RECIP_A)
const pb = await mk(B, RECIP_B)
if (pa.root !== pb.root) throw new Error("root mismatch")

const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1u = (p) => arr(be32(p[0]) + be32(p[1]))
const G2u = (u) => arr(be32(u.pi_b[0][1]) + be32(u.pi_b[0][0]) + be32(u.pi_b[1][1]) + be32(u.pi_b[1][0]))
const G1 = (p) => arr(be32(p[0]) + be32(p[1]))

const L = [
    "// AUTO-GENERATED by tools/gen-distributor-fixture-domain.mjs — do not edit by hand.",
    "// Two depth-2 proofs from distinct members, each bound to a distinct recipient address,",
    "// all scoped to one campaign whose scope is DOMAIN-BOUND to CONTRACT:",
    "//   scope = keccak256( ascii(CONTRACT strkey) || SCOPE_SEED ) >> 8.", "",
    `pub const SCOPE_SEED: [u8; 32] = ${arr(SCOPE_SEED_HEX)};`,
    `/// The distributor contract address the campaign scope is bound to; the test registers here.`,
    `pub const CONTRACT: &str = "${CONTRACT}";`,
    `pub const ROOT: [u8; 32] = ${arr(be32(pa.root))};`,
    `pub const RECIPIENT_A: &str = "${RECIP_A}";`,
    `pub const RECIPIENT_B: &str = "${RECIP_B}";`,
    "", "// Member A -> RECIPIENT_A", `pub const NUL_A: [u8; 32] = ${arr(be32(pa.nullifier))};`,
    `pub const A_A: [u8; 64] = ${G1u(pa.u.pi_a)};`,
    `pub const A_B: [u8; 128] = ${G2u(pa.u)};`,
    `pub const A_C: [u8; 64] = ${G1u(pa.u.pi_c)};`,
    "", "// Member B -> RECIPIENT_B", `pub const NUL_B: [u8; 32] = ${arr(be32(pb.nullifier))};`,
    `pub const B_A: [u8; 64] = ${G1u(pb.u.pi_a)};`,
    `pub const B_B: [u8; 128] = ${G2u(pb.u)};`,
    `pub const B_C: [u8; 64] = ${G1u(pb.u.pi_c)};`,
    "", "// Verification key (depth 2)",
    `pub const VK_ALPHA: [u8; 64] = ${G1(vkey.vk_alpha_1)};`,
    `pub const VK_BETA: [u8; 128] = ${arr(be32(vkey.vk_beta_2[0][1]) + be32(vkey.vk_beta_2[0][0]) + be32(vkey.vk_beta_2[1][1]) + be32(vkey.vk_beta_2[1][0]))};`,
    `pub const VK_GAMMA: [u8; 128] = ${arr(be32(vkey.vk_gamma_2[0][1]) + be32(vkey.vk_gamma_2[0][0]) + be32(vkey.vk_gamma_2[1][1]) + be32(vkey.vk_gamma_2[1][0]))};`,
    `pub const VK_DELTA: [u8; 128] = ${arr(be32(vkey.vk_delta_2[0][1]) + be32(vkey.vk_delta_2[0][0]) + be32(vkey.vk_delta_2[1][1]) + be32(vkey.vk_delta_2[1][0]))};`,
    ""]
vkey.IC.forEach((p, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(p)};`))
L.push("")
writeFileSync(OUT, L.join("\n"))
console.log(`OK: distributor ground-truth verified (domain-bound). CONTRACT = ${CONTRACT}`)
process.exit(0)
